#!/usr/bin/env bash
# compact-instructions.sh - PreCompact hook：stdout 会成为压缩摘要的指令，不占常驻上下文。

cat <<'EOF'
摘要用简体中文写，必须保留：
1. 用户的全部要求，逐条编号并标状态（待做、进行中、完成、阻塞），包括中途追加和插进来的；用户的原话要点照抄。
2. 用户的纠正、约束、授权，以及用户明确指定的命名、文件、工具和做法。
3. 已定的决定和依据；已验证的事实标明「已验证」，附命令或证据文件路径。
4. 改过的文件的完整路径、所在仓库与分支、提交号、是否已推送和部署；别的会话在同一仓库留下的未提交改动。
5. 仍在运行的后台任务、子代理、工作流和终端 tab 的 ID 与用途。
6. 状态文件、报告、brief 的路径，以及下一步和未完成项。
不保留探索过程、已放弃的方案和工具输出原文。
EOF
